// Phase 3 data migration: dump live Neon data to a D1-ready SQL file.
//
// Usage:
//   DATABASE_URL="postgres://..." node scripts/export-neon-to-d1.mjs
//   wrangler d1 execute eurosnap --remote --file=db/data-export.sql
//
// Migrates users, watchers, notifications_sent (preserving primary keys so the
// notifications_sent -> watchers foreign key still resolves). availability_cache
// is intentionally skipped — it's a 2-hour cache that the cron regenerates, and
// skipping it avoids any timestamp-format mismatch.
//
// NOTE: requires Neon to be readable. If the compute quota is exhausted (HTTP
// 402) this will fail until the quota resets or the plan is upgraded.

import { neon } from "@neondatabase/serverless";
import { writeFileSync } from "node:fs";

const url = process.env.DATABASE_URL || process.env.STORAGE_URL;
if (!url) {
  console.error("Set DATABASE_URL to your Neon connection string.");
  process.exit(1);
}
const sql = neon(url);

const q = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "1" : "0";
  return `'${String(v).replace(/'/g, "''")}'`;
};

// Postgres timestamp -> SQLite 'YYYY-MM-DD HH:MM:SS' (UTC), matching datetime('now').
const ts = (v) => {
  if (!v) return "NULL";
  const iso = new Date(v).toISOString();
  return `'${iso.replace("T", " ").slice(0, 19)}'`;
};

const lines = [];
lines.push("-- Generated by export-neon-to-d1.mjs");
lines.push("PRAGMA foreign_keys=OFF;");
lines.push("BEGIN TRANSACTION;");

const users = await sql`SELECT id, email, name, password_hash, google_id, tier, stripe_customer_id, stripe_subscription_id, amnesty, created_at FROM users ORDER BY id`;
for (const u of users) {
  lines.push(
    `INSERT INTO users (id,email,name,password_hash,google_id,tier,stripe_customer_id,stripe_subscription_id,amnesty,created_at) VALUES (${q(u.id)},${q(u.email)},${q(u.name)},${q(u.password_hash)},${q(u.google_id)},${q(u.tier)},${q(u.stripe_customer_id)},${q(u.stripe_subscription_id)},${u.amnesty ? 1 : 0},${ts(u.created_at)});`
  );
}

const watchers = await sql`SELECT id, email, route_id, date_from, date_to, passengers, active, created_at, unsubscribe_token, weekdays, time_slot_pref FROM watchers ORDER BY id`;
for (const w of watchers) {
  const dateFrom = typeof w.date_from === "string" ? w.date_from : new Date(w.date_from).toISOString().slice(0, 10);
  const dateTo = typeof w.date_to === "string" ? w.date_to : new Date(w.date_to).toISOString().slice(0, 10);
  lines.push(
    `INSERT INTO watchers (id,email,route_id,date_from,date_to,passengers,active,created_at,unsubscribe_token,weekdays,time_slot_pref) VALUES (${q(w.id)},${q(w.email)},${q(w.route_id)},${q(dateFrom)},${q(dateTo)},${q(w.passengers)},${w.active ? 1 : 0},${ts(w.created_at)},${q(w.unsubscribe_token)},${q(w.weekdays)},${q(w.time_slot_pref)});`
  );
}

const notes = await sql`SELECT id, watcher_id, available_date, sent_at FROM notifications_sent ORDER BY id`;
for (const n of notes) {
  const availDate = typeof n.available_date === "string" ? n.available_date : new Date(n.available_date).toISOString().slice(0, 10);
  lines.push(
    `INSERT INTO notifications_sent (id,watcher_id,available_date,sent_at) VALUES (${q(n.id)},${q(n.watcher_id)},${q(availDate)},${ts(n.sent_at)});`
  );
}

lines.push("COMMIT;");
lines.push("PRAGMA foreign_keys=ON;");

writeFileSync("db/data-export.sql", lines.join("\n") + "\n");
console.log(`Exported ${users.length} users, ${watchers.length} watchers, ${notes.length} notifications -> db/data-export.sql`);
